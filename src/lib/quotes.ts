/** 按日期取当日一言（同一天固定同一句，SSR/CSR 一致，无随机） */
export function quoteForDay(date?: string): Quote {
  return QUOTES[quoteIndexForDay(date)]
}

/** 同上，但返回下标——供卡片做「定时轮换」时确定起点（Task 26-k） */
export function quoteIndexForDay(date?: string): number {
  if (QUOTES.length === 0) return 0
  if (!date) return 0
  const d = new Date(`${date}T00:00:00Z`)
  let seed: number
  if (Number.isNaN(d.getTime())) {
    // 日期串不合法时退化为对字符串做稳定 hash
    seed = 0
    for (let i = 0; i < date.length; i++) seed = (seed * 31 + date.charCodeAt(i)) % 100000
  } else {
    const start = Date.UTC(d.getUTCFullYear(), 0, 1)
    seed = Math.floor((d.getTime() - start) / 86400000)
  }
  return seed % QUOTES.length
}
