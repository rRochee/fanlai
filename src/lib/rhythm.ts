/** 该季节有节奏内容的月份（月历 chip 用） */
export function rhythmMonthsFor(season: string): number[] {
  const m = RHYTHM_BY_SEASON[season]
  return m ? Object.keys(m).map(Number).sort((a, b) => a - b) : []
}

/** 取某季某月的节奏内容；没有则 null */
export function rhythmFor(season: string, month: number): MonthRhythm | null {
  return RHYTHM_BY_SEASON[season]?.[month] ?? null
}
